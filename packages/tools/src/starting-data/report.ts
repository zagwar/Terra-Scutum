import { writeFileSync } from 'node:fs';
import type {
  ImfSnapshot,
  StartingDataConfig,
  StartingDataResult,
  WorldBankSnapshot,
} from './build-starting-data';
import { WORLD_CODES } from './snapshot-sources';

/** Sources that differ by more than this share are listed in the report. */
const DISAGREEMENT_SHARE = 0.05;

const formatPeople = (n: number) =>
  n >= 1e9
    ? `${(n / 1e9).toFixed(2)} bn`
    : n >= 1e6
      ? `${(n / 1e6).toFixed(n >= 1e8 ? 0 : 1)} M`
      : Math.round(n).toLocaleString('en');
const formatGdp = (millions: number) =>
  millions >= 1e6
    ? `${(millions / 1e6).toFixed(2)} T`
    : millions >= 1000
      ? `${(millions / 1000).toFixed(1)} bn`
      : `${Math.round(millions)} M`;
const percent = (share: number) => `${share >= 0 ? '+' : ''}${(share * 100).toFixed(0)}%`;

/**
 * `packages/tools/starting-data/report.md`: every country's starting data in
 * one table, the world totals, and where the IMF and the World Bank disagree
 * (a rough measure of how accurate the numbers are).
 */
export function writeStartingDataReport(
  path: string,
  config: StartingDataConfig,
  result: StartingDataResult,
  imf: ImfSnapshot,
  worldBank: WorldBankSnapshot,
  countryName: (id: string) => string,
): void {
  const { file } = result;
  const year = String(file.year);
  const lines: string[] = [];
  const imfCode = (code: string) => config.sourceCodes[code]?.imf ?? code;
  const worldBankCode = (code: string) => config.sourceCodes[code]?.worldBank ?? code;
  const worldPopulation = worldBank.population[WORLD_CODES.worldBank];
  const worldGdp = imf.values.NGDPD[WORLD_CODES.imf]?.[year];
  const total = file.countries.reduce(
    (sum, c) => ({ population: sum.population + c.population, gdp: sum.gdp + c.gdpMillionUsd }),
    { population: 0, gdp: 0 },
  );

  lines.push(
    '# Starting data report (F71)',
    '',
    'Generated by `npm run import:starting-data`; do not edit. Sources:',
    '',
    ...Object.values(file.sources).map(
      (s) => `- ${s.title}${s.edition ? ` (${s.edition})` : ''}${s.url ? `: ${s.url}` : ''}`,
    ),
    '',
    `**${file.countries.length} countries** in ${file.year}: ${formatPeople(total.population)} people, ` +
      `GDP US$${formatGdp(total.gdp)}` +
      (worldPopulation !== undefined && worldGdp !== undefined
        ? ` (the whole world: ${formatPeople(worldPopulation)} people (World Bank), GDP US$${formatGdp(worldGdp * 1000)} (IMF); ` +
          "the World Bank's total has no Taiwan, and the small countries left out of the game are missing from the game's total)"
        : '') +
      '.',
    '',
  );

  // Government types.
  const byType = new Map<string, number>();
  for (const c of file.countries)
    byType.set(c.governmentType, (byType.get(c.governmentType) ?? 0) + 1);
  lines.push('## Government types', '');
  for (const [type, count] of [...byType].sort((a, b) => b[1] - a[1]))
    lines.push(`- ${type}: ${count}`);
  lines.push('');

  // How well the sources agree.
  lines.push(
    '## Where the sources disagree',
    '',
    `Countries where the IMF's and the World Bank's ${year} figures differ by more than ` +
      `${DISAGREEMENT_SHARE * 100}% (shown as the IMF compared with the World Bank). The game uses the World Bank ` +
      "for population (based on the UN's World Population Prospects) and the IMF for GDP. " +
      'Differences usually come from national census figures versus UN estimates, or from ' +
      'territories counted differently.',
    '',
  );
  const disagreements: string[] = [];
  for (const c of file.countries) {
    const imfPopulation = imf.values.LP[imfCode(c.id)]?.[year];
    const wbPopulation = worldBank.population[worldBankCode(c.id)];
    if (imfPopulation !== undefined && wbPopulation !== undefined) {
      const share = (imfPopulation * 1e6) / wbPopulation - 1;
      if (Math.abs(share) > DISAGREEMENT_SHARE)
        disagreements.push(`- ${countryName(c.id)}: population ${percent(share)}`);
    }
    const imfGdp = imf.values.NGDPD[imfCode(c.id)]?.[year];
    const wbGdp = worldBank.gdpLatest[worldBankCode(c.id)];
    if (imfGdp !== undefined && wbGdp !== undefined && wbGdp[0] === file.year) {
      const share = (imfGdp * 1e9) / wbGdp[1] - 1;
      if (Math.abs(share) > DISAGREEMENT_SHARE)
        disagreements.push(`- ${countryName(c.id)}: GDP ${percent(share)}`);
    }
  }
  lines.push(...(disagreements.length > 0 ? disagreements : ['- none']), '');

  lines.push(
    '## Merged territories with no figures',
    '',
    "Left out (tiny, uninhabited, or already counted in the country's own figures): " +
      (result.skippedTerritories.length > 0 ? result.skippedTerritories.join(', ') : 'none') +
      '.',
    '',
  );

  // Every country.
  lines.push(
    '## Every country',
    '',
    `Population and GDP (nominal US$) in ${file.year}. Sources: W = World Bank, I = IMF, E = estimate.`,
    '',
    '| Country | Population | GDP | GDP per person | Government | Sources | Notes |',
    '|---|---:|---:|---:|---|---|---|',
  );
  const letter: Record<string, string> = { worldBank: 'W', imfWeo: 'I', estimate: 'E' };
  for (const c of [...file.countries].sort((a, b) => b.gdpMillionUsd - a.gdpMillionUsd)) {
    const perPerson = Math.round((c.gdpMillionUsd * 1e6) / c.population).toLocaleString('en');
    const sources = `${letter[c.populationSource]} / ${letter[c.gdpSource]}${c.gdpYear ? ` (GDP ${c.gdpYear})` : ''}`;
    const notes = (c.notes ?? []).join(' · ').replace(/\|/g, '/');
    lines.push(
      `| ${countryName(c.id)} | ${formatPeople(c.population)} | ${formatGdp(c.gdpMillionUsd)} | $${perPerson} | ${c.governmentType} | ${sources} | ${notes} |`,
    );
  }
  lines.push('');
  writeFileSync(path, lines.join('\n'));
}
