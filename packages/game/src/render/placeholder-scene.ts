import { ArcRotateCamera } from '@babylonjs/core/Cameras/arcRotateCamera';
import type { AbstractEngine } from '@babylonjs/core/Engines/abstractEngine';
import { DirectionalLight } from '@babylonjs/core/Lights/directionalLight';
import { HemisphericLight } from '@babylonjs/core/Lights/hemisphericLight';
import { StandardMaterial } from '@babylonjs/core/Materials/standardMaterial';
import { Color3, Color4 } from '@babylonjs/core/Maths/math.color';
import { Vector3 } from '@babylonjs/core/Maths/math.vector';
import { CreateIcoSphere } from '@babylonjs/core/Meshes/Builders/icoSphereBuilder';
import { CreateLineSystem } from '@babylonjs/core/Meshes/Builders/linesBuilder';
import { Scene } from '@babylonjs/core/scene';

const GRID_HALF_SIZE = 20;
const MARKER_TURNS_PER_SECOND = 0.03;

/**
 * The empty 3D scene shown until the world map exists (F01): a reference grid
 * and one slowly turning marker, so it's visible that the 3D engine is running.
 * Everything is generated by code. Replaced by the map in F01.
 */
export function createPlaceholderScene(engine: AbstractEngine, animate: boolean): Scene {
  const scene = new Scene(engine);
  scene.clearColor = new Color4(0.02, 0.03, 0.05, 1);

  // Fixed camera for now; the strategy camera (pan, zoom, rotate) is feature F03.
  const camera = new ArcRotateCamera(
    'camera',
    -Math.PI / 2.6,
    1.08,
    15,
    new Vector3(0, 1, 0),
    scene,
  );
  camera.minZ = 0.1;
  camera.maxZ = 500;

  const sky = new HemisphericLight('sky-light', new Vector3(0, 1, 0), scene);
  sky.intensity = 0.55;
  sky.groundColor = new Color3(0.1, 0.12, 0.16);
  const sun = new DirectionalLight('sun-light', new Vector3(-0.6, -1, 0.4), scene);
  sun.intensity = 1.1;

  // Ground grid: thin lines every unit, brighter lines every five.
  const minorLines: Vector3[][] = [];
  const majorLines: Vector3[][] = [];
  for (let i = -GRID_HALF_SIZE; i <= GRID_HALF_SIZE; i++) {
    const target = i % 5 === 0 ? majorLines : minorLines;
    target.push([new Vector3(i, 0, -GRID_HALF_SIZE), new Vector3(i, 0, GRID_HALF_SIZE)]);
    target.push([new Vector3(-GRID_HALF_SIZE, 0, i), new Vector3(GRID_HALF_SIZE, 0, i)]);
  }
  const minorGrid = CreateLineSystem('grid-minor', { lines: minorLines }, scene);
  minorGrid.color = new Color3(0.1, 0.15, 0.2);
  minorGrid.isPickable = false;
  const majorGrid = CreateLineSystem('grid-major', { lines: majorLines }, scene);
  majorGrid.color = new Color3(0.2, 0.3, 0.4);
  majorGrid.isPickable = false;

  // The marker: a faceted sphere.
  const marker = CreateIcoSphere('marker', { radius: 2, subdivisions: 2, flat: true }, scene);
  marker.position.y = 2.6;
  const material = new StandardMaterial('marker-material', scene);
  material.diffuseColor = new Color3(0.27, 0.45, 0.62);
  material.specularColor = new Color3(0.25, 0.25, 0.25);
  material.specularPower = 24;
  marker.material = material;
  marker.rotation.y = 0.4;

  if (animate) {
    scene.onBeforeRenderObservable.add(() => {
      marker.rotation.y += (engine.getDeltaTime() / 1000) * MARKER_TURNS_PER_SECOND * 2 * Math.PI;
    });
  }

  return scene;
}
